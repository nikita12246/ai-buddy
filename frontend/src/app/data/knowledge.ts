const stopWords = new Set(['где','как','что','это','для','или','мне','моя','мой','мои','по','на','в','из','и','а','к','с','о','об','у','the','to']);
const suffixes = ['иями','ями','ами','ого','ему','ыми','ий','ый','ая','ое','ые','ов','ах','ях','ом','ем','ам','ям','ей','ой','ы','а','я','и','е','у','ю','ь','й'];
const stem = (word:string) => { const w=word.toLowerCase(); return w.length>4 ? w.replace(new RegExp(`(${suffixes.join('|')})$`),'') : w; };
const tokens = (value:string) => value.toLowerCase().match(/[a-zа-яё0-9]+/gi)?.map(stem).filter(t=>t.length>1&&!stopWords.has(t))||[];

export function searchDemoKnowledge(question:string) {
  const query=tokens(question);
  const ranked=demoKnowledge.map(doc=>{
    const title=tokens(doc.title).join(' '), body=tokens(`${doc.summary} ${doc.body} ${doc.topic} ${doc.project} ${doc.team}`).join(' ');
    const score=query.reduce((sum,term)=>sum+(title.includes(term)?3:0)+(body.includes(term)?1:0),0);
    return {doc,score};
  }).filter(item=>item.score>0).sort((a,b)=>b.score-a.score).slice(0,5);
  return ranked.map(item=>item.doc);
}

export function answerFromDemoSources(docs:KnowledgeDocument[]) {
  if(!docs.length) return 'В демонстрационном корпусе не нашлось материала, который подтверждает ответ. Уточни вопрос или попроси наставника найти актуальный источник.';
  return docs.slice(0,3).map(doc=>doc.summary).join(' ');
}
